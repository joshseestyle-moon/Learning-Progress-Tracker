const VALID_LANGS = ['zh-TW', 'en', 'ja'];
let _lang = VALID_LANGS.includes(localStorage.getItem('lang')) ? localStorage.getItem('lang') : 'zh-TW';

export const getLang = () => _lang;

export function setLang(lang) {
  if (!VALID_LANGS.includes(lang)) return;
  _lang = lang;
  localStorage.setItem('lang', lang);
  window.dispatchEvent(new Event('langchange'));
}

export function t(key, vars = {}) {
  const str = TRANSLATIONS[_lang]?.[key] ?? TRANSLATIONS['zh-TW']?.[key] ?? key;
  return str.replace(/\{(\w+)\}/g, (_, k) => (vars[k] !== undefined ? vars[k] : ''));
}

export function tErr(msg) {
  return t('err.' + msg) || msg;
}
